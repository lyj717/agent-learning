"""pytest 入门演示：一个测试到底长什么样。

这个文件既是讲解，也是真能跑的测试：
    .venv\\Scripts\\python.exe -m pytest tests\\test_pytest_demo.py -v

为什么放在 tests/ 里：pytest 只认特定的命名（文件 test_*.py、函数 test_*），
放在这个目录，仓库根目录跑 pytest 时也会自动带上它。
"""

# ============================================================
# 被测的东西：一个纯函数
# ============================================================
#
# 测试测的是「函数的行为」，所以先得有个函数。
# 真实项目里它写在别的文件里、由测试 import 进来；
# 这里为了让你一眼看全，就放在同一个文件里。


def greet(name: str, excited: bool = False) -> str:
    """打招呼。excited=True 时在结尾加一个感叹号。"""
    text = f"你好，{name}"
    return text + "!" if excited else text


# ============================================================
# 测试：每个都是同一个三段式
# ============================================================
#
#     准备（Arrange）→ 调用（Act）→ 断言（Assert）
#
# 函数名要写清「在测什么」——测试失败时，这一行名字就是说明书。
# 断言就用普通的 assert，不需要 assertEqual 那种东西。


def test_greet_returns_text_with_name():
    """最基本的一条：名字应该出现在结果里。"""
    # 准备 + 调用
    result = greet("小明")
    # 断言
    assert result == "你好，小明"


def test_greet_excited_adds_exclamation_mark():
    """excited=True 时结尾要多一个感叹号。"""
    result = greet("小明", excited=True)
    assert result == "你好，小明!"


def test_greet_default_is_quiet():
    """不传 excited 时，结果和 excited=False 一样——测的是「默认值」。"""
    assert greet("小明") == greet("小明", excited=False)


# ============================================================
# 关于写测试的几个要点
# ============================================================
#
# 1. 命名决定一切：文件要叫 test_*.py，函数要叫 test_*，
#    不然 pytest 根本不会收集它（这就是「测试没跑」最常见的原因）。
#
# 2. 一个测试只测一件事。名字里写清测的是什么行为，
#    失败时你从名字就能知道坏在哪儿，不用去读代码。
#
# 3. 测试要快、要独立、不要连网。
#    所以对外部世界的依赖（网络、密钥、文件）应该被隔离在外面——
#    这也是为什么 chat_cli 把「拼请求」和「发请求」拆成了两个函数。
#
# 4. 断言失败时 pytest 会把两边的值都打出来，比如：
#
#        E       assert '你好，小明' == '你好，小明!'
#        E         - 你好，小明!
#        E         + 你好，小明
#
#    一眼就看得出少了感叹号。所以断言写得越具体，出错时越好查。
#
# 5. 最重要的习惯：**写完测试，先让它失败一次**。
#    把上面 greet 里那个 + "!" 删掉，再跑一遍测试，
#    你会看到第二个测试红掉——这才证明它真的在测东西。
#    一个从没红过的测试，你无法相信它。
#
# 6. 和 tests/test_check_env.py 对比着看会有帮助：
#    那边测的是「运行环境」，要跑子进程、看文件系统，所以显得长；
#    这边测的是纯函数——输入进去、输出出来，几毫秒就跑完。
#    你现在要写的 chat_cli 测试，属于后面这种。
