"""Day45 前置：认识 BM25 的词项输入，固定中文单字和英文标识符的处理规则。"""

import re


def main() -> None:
    """用独立字符串展示输入形状，不执行检索或融合。"""
    print("Week6 要用同一批题比较检索改动。Day45 给原向量检索增加关键词通道。")
    print(
        "本演示解决该通道的输入问题：文字要先变成词项列表；A 会用同一规则处理问题和片段。"
    )
    print(
        "\n一、是什么：词项就是参与匹配的文字单位，可以是英文单词、标识符或中文单字。"
    )
    print("二、为什么：BM25 接收 list[str]；原始字符串不是本课约定的输入形状。")
    print("三、场景：资料中写 Tool_A，问题中写 tool_a，希望它们能匹配。")
    text = "Tool_A 调用失败 503！"
    print(f"\n四、代码：原文={text!r}")
    print(f"只按空白切开={text.split()}；中文‘调用失败’仍连在一起。")
    normalized = text.casefold()  # casefold()：统一大小写，返回新字符串。
    # re.findall(正则模式, 字符串)：按出现顺序返回所有匹配的字符串，不修改原文。
    tokens = re.findall(r"[a-z_][a-z_0-9]*|[0-9]+|[\u4e00-\u9fff]", normalized)
    print(f"本课固定规则={tokens}")
    print("模式三部分：英文或下划线开头的标识符；连续数字；一个中文字符。标点不收录。")
    print("例如 sorted 和 score 各保留为一个词项，中文‘排序’变成‘排’、‘序’。")
    print(
        "\n五、边界：这是可复现的教学规则，没有做中文词语识别、同义词扩展或停用词过滤。"
    )
    print(
        "问题和片段必须用相同规则。匹配到同一个字，只能帮助排名，不能证明片段能回答。"
    )
    print("练习已提供同样规则的 tokenize_text；本单元保持它不变，避免同时改多个因素。")


if __name__ == "__main__":
    main()
