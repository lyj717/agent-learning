"""Day48：用独立人工例子说明先固定方案、后查看留出结果的作用。"""

from copy import deepcopy


def main() -> None:
    """比较保存独立配置与事后改配置，不读取本周真实题目或运行检索。"""
    print("Week6 最后要交一份能说明收益、代价与限制的评测报告。")
    print("本演示负责其中的留出检查：先保存打算检验的方案，再看未参与调试的结果。")
    print("学完能说明检验的是哪个版本，以及看完结果后调整方案应怎样记账。")
    print("下面的配置、题号和分数都是 AI 人工示意，不是你的留出结果。")

    print("\n一、这是什么：冻结就是保存这次准备检验的配置和选择理由。")
    print("不只是一个方案名称；资料、切分、k、排名规则、提示词和模型参数也要固定。")
    print("为什么：若看见结果差就改 k，再只报最后一轮，读者看不出这批题参与过调试。")
    print("场景：开发题上选了关键词检索；要用另外三道题检查这个既定选择。")
    working = {"scheme": "keyword", "k": 2}
    # deepcopy(对象)：复制包括内部列表/字典在内的独立值；改原对象不会跟着改副本。
    frozen = deepcopy(working)
    print(f"查看结果前的方案={frozen}")
    print("第一次检查的人工示意结果：3 题答对 1 题。")

    print("\n二、代码：保存的选择和后来尝试的选择是两份记录。")
    working["k"] = 4
    print(f"看完结果后尝试的新配置={working}")
    print(f"原冻结配置仍为={frozen}，原结果也仍是 1/3。")
    print("改成 k=4 再跑同三题可以帮助开发，但这三题已经参与调试。")
    print("若要检查新配置对未参与调试问题的表现，需要另一批合适的新题。")

    print("\n三、注意什么：本日入口会保存文件摘要，发现配置改变就拒绝沿用旧冻结记录。")
    print("摘要只是识别文件是否变化的标记，不能证明一个人从没手动看过结果。")
    print("同配置因请求失败而复测也要保留旧轮；不跨轮挑最好答案拼成一轮。")
    print("本次六道留出题：两种方案比较检索，只给事先选定的一种方案生成回答。")
    print("因此可比较两组检索指标；六题的答案与引用指标只描述所选方案。")


if __name__ == "__main__":
    main()
