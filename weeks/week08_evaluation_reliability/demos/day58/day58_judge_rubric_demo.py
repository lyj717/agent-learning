"""Day58 演示一：模型裁判——让模型按评分项读回答，并输出可比较的结构化结论。

Week08 要给问答加自动评测。Day57 的规则层只能看字面；本演示讲第二层：
用模型当裁判，判断回答是否正确、引用是否支持结论。
学完应能说清评分项为什么这样拆、为什么输出 JSON、以及裁判为什么不能替代人工。
全部离线，不调用模型；练习写 prompt 与解析。
"""


def say(text: str = "") -> None:
    """打印一行；不传参数时只输出一个空行。"""
    print(text)


def main() -> None:
    """按用途、评分项、场景、输出结构、边界的顺序讲一次模型裁判。"""
    say("Day57 的规则层能抓格式、缺要点、引用编号越界，也抓到了 q03 的回归。")
    say("但 q04 那种「字面齐全、意思说反」的回答，规则判通过。")
    say("本演示负责第二层：让模型按评分项读回答，输出可比较的结构化结论。")
    say("学完应能说清评分项为什么这样拆、裁判为什么不能替代人工；")
    say("练习 A 写裁判 prompt，练习 B 解析裁判输出。")

    say("\n一、这是什么")
    say("模型裁判（LLM-as-judge）是把问题、回答和原文一起交给模型，")
    say("让它按固定的评分项判断，并只用 JSON 返回结论。")
    say("它不是「再问一遍答案」，而是让模型做一次带评分标准的阅读。")

    say("\n二、为什么需要它")
    say("规则层便宜、确定，但只认字面：同义改写、否定、结论相反都可能漏。")
    say("人工最准，但每次改代码都找人重看几十条，既慢又不可重复。")
    say("模型裁判能读语义，成本比人低，适合在人工抽样之前做一层筛查。")

    say("\n三、具体场景：设备借用问答")
    say("问题：借用投影仪时，在哪里登记、要带什么？")
    say("原文：借用前到前台登记，并带上工牌；归还时交回遥控器与电源线。")
    say("回答：不用去前台登记，也不用带工牌。")
    say("规则层：必须出现「前台」「工牌」——都出现了，判通过。")
    say("人工/裁判：这句话把做法说反了，answer_ok 应为 false。")

    say("\n四、评分项怎么拆")
    say("answer_ok：回答是否正确且完整地回答问题，只依据给出的原文；")
    say("  true 表示结论与原文一致、要点没有漏；false 表示有错、答非所问或漏关键步骤。")
    say("citation_ok：被引用的原文是否支持回答中的结论；")
    say("  没有引用时填 null（不适用），不要硬判 true 或 false。")
    say("reason：一两句话说明判断依据，方便人工复核分歧。")
    say("三项分开的理由：回答正确但引用不支持，和回答错误，是两种不同的问题；")
    say("合并成一个分数，后面就分不清该改生成还是改引用。")

    say("\n五、为什么用二值 + 理由，不用 1~10 分")
    say("二值容易和人工标签对齐，也容易统计一致/分歧；")
    say("分数需要额外约定「7 分和 8 分差在哪」，不同轮次、不同模型的刻度会漂。")
    say("需要更细的粒度时，应该增加评分项，而不是把一格拉成十分。")

    say("\n六、输出结构：只给三个键")
    say('{"answer_ok": true, "citation_ok": null, "reason": "……"}')
    say("请求时开 JSON 模式、温度 0，并在 prompt 里明确「只输出这个 JSON 对象」。")
    say("温度 0 只是降低随机性，不保证每次完全相同；服务商和模型版本也会影响结果。")

    say("\n七、裁判的偏差与边界")
    say("1. 长度偏差：写得长的回答容易被判得更完整，哪怕关键点更少。")
    say(
        "2. 位置偏差：多个候选项按顺序比较时，先后位置会影响结论；这里一次只判一份，影响较小。"
    )
    say("3. 自我偏好：用同一个模型生成、又用它判分，可能偏向自己的写法。")
    say(
        "4. 证据不足：原文没给全时，模型可能拿常识补；prompt 要限制「只依据给出的原文」。"
    )
    say("5. 小样本：8 题只能看分歧，不能报「准确率 87.5%」这种总体结论。")
    say(
        "6. 成本与延迟：每判一题一次调用；不适合每次提交都跑，放在手动入口或受控预算里。"
    )

    say("\n八、和人工标签怎么配合")
    say("先让人独立判一遍并写下理由，再跑裁判，最后逐题比较；")
    say("一致率高只说明这一小批上两边接近，不说明裁判「对」。")
    say(
        "真正要看的是分歧题：读裁判的理由和原文，判断谁错，再决定改 prompt 还是改标签。"
    )

    say("\n下一步：读演示二，看模型输出的 JSON 为什么要先解析、再逐项校验；")
    say("然后写练习 A 的 build_judge_messages 和 B 的 parse_judge_verdict。")


if __name__ == "__main__":
    main()
