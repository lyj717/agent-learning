"""Day61 演示：五类失败模式，各自能被什么确定性信号抓住。

Week08 最后的交付是「失败清单 + 能进 CI 的确定性检查」。
本演示用最小示意说明：无限循环、工具误用、幻觉引用、格式崩坏、越权注入
分别该看什么信号，以及为什么这些检查不依赖模型输出。
全部离线，不调用模型。
"""


def say(text: str = "") -> None:
    """打印一行；不传参数时只输出一个空行。"""
    print(text)


def main() -> None:
    """按用途、五类模式、判据、边界的顺序讲一次失败清单。"""
    say("Day57～60 有了评测、裁判和一次优化对照；今天回答：")
    say("上线前后最该防的五类故障，各自用什么确定性信号抓。")
    say("本演示只讲判据；练习写五个检查函数，检查器会用正常版/故障版验收。")

    say("\n一、什么是失败模式与确定性检查")
    say("失败模式：同一类故障反复出现，换一道题也还会犯。")
    say("确定性检查：不改模型输出、不看语义，只查计数、集合、异常和结构；")
    say("同样的输入永远给同样的通过/失败，适合放 CI。")

    say("\n二、无限循环")
    say("现象：Agent 反复调用工具或重试，步数一直涨。")
    say("示意：max_steps=5，实际走了 9 步。")
    say("信号：步数 <= 上限；超出就失败。看计数器，不看耗时。")
    say("注意：用时间做上限会受机器负载影响；步数是确定的。")

    say("\n三、工具误用")
    say("现象：模型点了不存在的工具，或给工具传了多余/缺失参数。")
    say("示意：dispatch('delete_file', {...}) 仍然返回成功。")
    say("信号：未知工具、参数键不匹配时必须抛错；检查用 pytest.raises。")
    say("注意：检查的是分发层，不是模型是否会点错；模型点错由这一层拦住。")

    say("\n四、幻觉引用")
    say("现象：回答里的 cited_ids 有一个编号不在本次证据里。")
    say("示意：evidence 是 L40-L42，回答却引用 L99-L100。")
    say("信号：answered 时 cited_ids 非空，且每个都包含在 evidence_ids 里。")
    say("注意：这只证明编号没编造，不证明片段支持结论；语义支持仍靠裁判/人工。")

    say("\n五、格式崩坏")
    say("现象：回答缺 status/answer/cited_ids，或 status 不在允许值里。")
    say("示意：parse('{\"foo\": 1}') 没有报错，直接返回了字典。")
    say("信号：解析后键集合、字段类型、允许值三项校验；不合规抛 FormatError。")
    say("注意：JSON 语法对但结构错也算崩坏；不要靠正则补键。")

    say("\n六、越权与注入")
    say("现象：工具收到 delete_file，或路径是 ../secret。")
    say("示意：authorize('delete_file', 'notes/a.md') 返回 True。")
    say("信号：工具名必须在允许列表；路径规范化后必须在沙箱目录内；")
    say("      越权时抛 PermissionError，而不是返回一段错误文本。")
    say("注意：白名单比黑名单稳；不要用字符串包含判断路径。")

    say("\n七、测试要有「故障版」")
    say("只测正常路径，检查可能永远通过；要拿一个故意坏掉的实现验证它会失败。")
    say("本课的检查器会把环境切到 DAY61_VARIANT=bad，再跑你的五个检查：")
    say("正常版应无异常，故障版应抛 AssertionError；少一个都说明检查没咬住。")

    say("\n八、边界")
    say("1. 这些检查不判断回答对不对，只守结构、计数、集合和权限。")
    say("2. 断言要具体：不要只写 assert result，要写清楚比较的是哪个字段。")
    say("3. 检查函数失败时抛 AssertionError，不要吞异常或返回 False。")
    say("4. 时间、随机数、外部服务不能作为确定性判据。")

    say("\n下一步：在练习里实现五个 check_* 函数，再跑检查器与 pytest。")


if __name__ == "__main__":
    main()
