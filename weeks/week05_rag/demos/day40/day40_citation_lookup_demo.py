"""Day 40：按原片段 id 找回引用，区分编号有效与原文支持。

使用本文件自己的人工原文和字典，演示查找已有编号与拒绝未知编号；
语义支持用预先写明的人工对照说明，不实现完整模型返回校验器。
"""


def main() -> None:
    """对照有效编号、未知编号和同一引用下的不同结论。"""
    print("Day 40｜引用编号存在，答案就一定有依据吗？")
    print("\n这份演示在本周目标中的作用")
    print("本周要做带引用的资料问答。模型给出引用编号后，程序要能找回对应原文。")
    print("本演示讲最小的编号回查，并区分“引用能找到”和“原文支持回答”。")
    print("学完应能按原片段 id 定位出处、拒绝未知编号，读原文判断结论是否有依据。")
    print("后续练习 B 会把编号回查用于完整返回格式检查；它不能代替语义核对。")

    print("\n1. 这是什么")
    print("引用回查就是拿引用编号到本次证据表里找对应记录。这里用 Python 字典演示。")
    print("字典的键是原片段 id，值保存正文、来源、原行范围，不采用数据库整数编号。")

    print("\n2. 为什么需要它")
    print("模型可能写出本次材料里不存在的编号；程序不能给这种编号拼造来源。")
    print("就算编号存在，回答仍可能多说了原文没有的信息，需要继续对照原文。")

    print("\n3. 场景与数据来路")
    print("下面原文和来源名由 AI 手写用于教学，没有打开任何同名磁盘文件。")
    print("来源名：rules/locker.md")
    print("  原行 1：存包柜说明")
    print("  原行 2：存包柜每次使用限四小时。")
    print("  原行 3：使用结束后请取走全部物品。")
    known_id = "rules/locker.md#L2-L3"
    evidence_by_id = {
        known_id: {
            "source": "rules/locker.md",
            "line_start": 2,
            "line_end": 3,
            "text": "存包柜每次使用限四小时。\n使用结束后请取走全部物品。",
        }
    }
    print(f"本次证据表只收录一条：{known_id}，正文取上面第 2～3 行。")

    print("\n4. 代码与实际结果")
    print("本例只使用字典，无需导入新库；dict.get(key, default=None) 按键查找值。")
    print("key 必填；default 可选，省略时查不到就返回 None，不自动生成记录。")
    print("证据表的有效记录都是字典，所以这里的 None 可以表示编号不存在。")
    print("下面两个引用编号也是 AI 手写的对照，尚未调用模型。")
    for cited_id in [known_id, "rules/locker.md#L7-L7"]:
        # 字典.get(编号)：有此键就取对应记录，查不到返回 None。
        matched = evidence_by_id.get(cited_id)
        print(f"\n尝试引用：{cited_id}")
        if matched is None:
            print("编号回查：拒绝。这个编号不在本次证据表中，不能拼造第 7 行出处。")
            continue
        print("编号回查：找到。")
        print(
            f"  来源={matched['source']}；原行={matched['line_start']}～{matched['line_end']}"
        )
        print(f"  原文：{matched['text']!r}")

    print("\n同一个有效引用，比较两条人工回答")
    print(f"两条回答都引用 {known_id}，因此字典查找都会成功。")
    print("下面判断是 AI 对照上述原文预先写明的教学说明，没有运行语义判定程序。")
    print("回答甲：每次最多使用四小时。")
    print("  原文支持：第 2 行写明了四小时限制。")
    print("回答乙：每次最多使用四小时，而且免费。")
    print("  原文只支持前半句，没有提供收费信息；不能用这个引用证明“免费”。")

    print("\n5. 注意什么")
    print("字典查找成功，只能说明编号属于本次材料，能取回对应来源与原文。")
    print("查找不会判断“免费”是不是事实，也不会判断原文是否支持答案的每个结论。")
    print("对资料不足的问题应明确说明缺少信息；引用了真实片段也不能补造未写明的事实。")
    print("这里只演示编号查找；模型返回的 JSON、字段类型与状态一致性由后续练习检查。")


if __name__ == "__main__":
    main()
