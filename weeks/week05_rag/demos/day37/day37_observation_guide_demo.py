"""Day 37 答疑：用不同教学输入说明怎样观察窗口范围与声明的出处。

帮助理解观察题 2/3 的操作，不运行学员函数，也不填写练习观察。
"""


def main() -> None:
    """打印带行号的两个小对照，帮助读懂观察题在比较什么。"""
    print("Day 37｜观察题 2/3 到底让你看什么？")
    print("\n这份演示在本周目标中的作用")
    print("RAG 切分后要保留可靠出处；这份答疑帮助你读懂窗口范围与来源位置。")
    print("学完应能说清一次窗口取了哪些行，以及一条片段声称自己来自哪里。")
    print("后续用这些观察核对自己的切分结果。这里是不同于练习的 AI 教学输入。")

    print("\n1. 这是什么")
    print("窗口范围 3～6 的意思：这一段取原文第 3、4、5、6 行，两端都包含。")
    print("声明的出处是片段记录里填写的来源和行范围，需要拿原文核对。")
    print("\n2. 为什么需要它")
    print("只看片段总数看不出重叠位置；只看到文件里有某句话也没核对它的具体出处。")
    print("\n3. 场景")
    print("先观察七行资料的两个相邻窗口，再核对设备说明中一条片段填写的行号。")

    print("\n4. 代码与实际结果：先学怎样观察范围")
    lines = ["登记", "核对", "签字", "领用", "保管", "归还", "销记"]
    # enumerate(序列, start=1)：同时给出原文行号和这一行的文字。
    for number, line in enumerate(lines, start=1):
        print(f"原文第 {number} 行：{line}")
    print("\n本例窗口最多 4 行，相邻窗口重叠 2 行。以下范围已经给定，不是切分函数。")
    for start, end in [(1, 4), (3, 6), (5, 7)]:
        print(f"窗口 {start}～{end}：原始行号={list(range(start, end + 1))}")
    print("观察方法：对照相邻两段，标出共有的原行号，再检查最后一段到哪里结束。")
    print("回到练习题 2 时，对比的是另一组输入：五行全文、窗口 3 行、重叠 0/1 行。")

    print("\n代码与实际结果：再学怎样核对填写的行号")
    original_lines = ["设备说明", "检查配件。", "核对编号。", "登记完成。"]
    for number, line in enumerate(original_lines, start=1):
        print(f"设备说明第 {number} 行：{line!r}")
    chunk_text = "核对编号。"
    for start, end in [(2, 2), (3, 3)]:
        # 切片左端从 0 开始，右端不包含；原文行范围则从 1 开始并包含两端。
        claimed_lines = original_lines[start - 1 : end]
        print(f"\n待核对片段正文：{chunk_text!r}")
        print(f"片段填写的范围：{start}～{end}")
        print(f"这个范围实际包含的原文：{claimed_lines!r}")
    print("观察方法：先读记录填的行号，再拿该位置的原文和片段正文逐项核对。")
    print("回到练习 B，还要检查来源文件是否一致，以及填写的终点是否超出原文。")

    print("\n5. 注意什么")
    print("这份答疑只示范观察方法。练习题用你自己程序的实际输出来写两三句观察即可。")
    print("不用重新写算法，也不用解释每一行代码；说明比较了什么、看到什么、怎样判断。")


if __name__ == "__main__":
    main()
