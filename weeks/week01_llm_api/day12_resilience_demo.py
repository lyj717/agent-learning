"""Day 12 材料一：上下文裁剪与容错（出错时不崩、说人话、能自己好）。

每一节都按同一个顺序来：
    这是什么 → 为什么需要它 → 一个具体场景 → 代码 → 要注意什么

**完全离线、不花钱**：第 4 节连的是一个必然连不上的本地端口，用真实报错演示重试。
    .venv\\Scripts\\python.exe weeks\\week01_llm_api\\day12_resilience_demo.py
"""

import time

import openai
from openai import OpenAI

# 连不上的地址：127.0.0.1 是本机，9 号端口没人监听，一定被拒绝。
# 用它来造「网络故障」，不花一分钱、也不依赖断网。
DEAD_BASE_URL = "http://127.0.0.1:9/v1"
# 假的密钥，反正连不上，不会发出去
FAKE_KEY = "sk-not-a-real-key-0123456789"

RETRYABLE_ERRORS = (
    openai.APIConnectionError,
    openai.APITimeoutError,
    openai.RateLimitError,
    openai.InternalServerError,
)


def section(title: str) -> None:
    print(f"\n{'=' * 56}\n{title}\n{'=' * 56}")


def say(*lines: str) -> None:
    for line in lines:
        print(line)


# ============================================================
section("1. 这是什么：容错要做的三件事")
# ============================================================

say(
    "容错不是「永远不失败」，而是失败时做到三件事：",
    "",
    "    ① 不崩——程序还在，用户还能继续打字（而不是甩一段 traceback 退出）",
    "    ② 说人话——告诉用户「网络连不上，请稍后再试」，而不是 APIStatusError: 429",
    "    ③ 能自己好的就先自己好——网络抖一下、限流几秒，自己等一等再试",
    "",
    "  为什么需要它：你现在这个程序，只要网络抖一下就直接带着一长串栈退出。",
    "  自己用还能忍，给别人用就是 bug。",
)


# ============================================================
section("2. 失败分两类：值得重试的，和不值得的")
# ============================================================

say(
    "  这条分界线是容错里最重要的判断——认错了，要么白等，要么白费：",
    "",
    "    值得重试（等一会儿再试很可能就成功）",
    "      APIConnectionError     连不上（网络抖动、DNS 抽风）",
    "      APITimeoutError        超时（服务端慢，不是你的错）",
    "      RateLimitError         429 限流（等几秒就好了）",
    "      InternalServerError    5xx 服务端自己出问题",
    "",
    "    不值得重试（再试一百次也一样，纯浪费时间和额度）",
    "      AuthenticationError    401 密钥不对",
    "      BadRequestError        400 请求写错了",
    "      NotFoundError          404 模型名或地址写错",
    "      UnprocessableEntityError 422 参数类型不对（比如 model 传了 null）",
    "",
    "  一句话记法：**4xx 里除了 429 都别重试；网络问题和 5xx 才重试。**",
)


# ============================================================
section("3. 重试怎么等：指数退避 + 抖动")
# ============================================================

BASE_DELAY = 1.0
say(
    "  最朴素的想法是「失败就重试」，但立刻重试等于往已经出问题的服务端再砸一次。",
    "  所以要等一等再试，而且越等越久：",
    "",
)

for attempt in range(1, 4):
    wait = BASE_DELAY * (2 ** (attempt - 1))
    say(f"    第 {attempt} 次失败 → 等 {wait:.1f} 秒再试")

say(
    "",
    "  这个「每失败一次就翻倍」的叫**指数退避**，1 → 2 → 4 → 8 ……",
    "",
    "  为什么还要加「抖动」（jitter）：如果一百个客户端同时被限流，",
    "  它们会同时在第 1 秒重试、同时在第 2 秒重试——本来只是短暂限流，",
    "  被这么一搞就变成了持续雪崩。所以真正的实现会在等待时间上加一点随机：",
    "      wait = base * 2 ** n * random(0.5, 1.0)   # 大致这样",
    "  大家等的时间错开，服务端就有喘息的机会。",
)

say(
    "",
    "  ——但是先别急着写！**SDK 自己就在重试。**",
    "",
    "  同一个「必然连不上」的地址，我测了两次（打开 SDK 的日志就能看见）：",
    "",
    "    默认客户端：",
    "      [SDK日志] Retrying request in 0.455628 seconds (retry 1 of 2)",
    "      [SDK日志] Retrying request in 0.937645 seconds (retry 2 of 2)",
    "      → 7.6 秒后才把错误抛给我",
    "    max_retries=0：",
    "      → 2.0 秒就抛出来了（一次就是一次）",
    "",
    "  也就是说 openai 这个库**默认替你重试 2 次**（也是指数退避 + 抖动）。",
    "  如果你自己再包一层「试 3 次」，最坏情况是 3 × 3 = **9 次请求**，",
    "  等待时间翻倍、日志里一堆 Retrying、账单也悄悄涨——这是最常见的坑之一。",
    "",
    "  所以本仓库的选择是：**建客户端时写 max_retries=0，把重试收归自己管**。",
    "  重试策略只该由一层说了算，不然你根本算不出来「最多会发几次请求」。",
)


# ============================================================
section("4. 真跑一次：连不上的时候，重试是怎么表现的")
# ============================================================

say(
    "  下面真的去连一个必然失败的地址（本机 9 号端口），每次等 0.3/0.6 秒，",
    "  好让你看清「重试」在时间上是什么样子（间隔调小了，不然要等很久）：",
    "",
)

# max_retries=0：把重试收归自己管，不然 SDK 在里面又偷偷重试两次，
# 上面写的 0.3s、0.6s 会被它那两次盖过去（实测每次要 7.6 秒）
client = OpenAI(api_key=FAKE_KEY, base_url=DEAD_BASE_URL, timeout=3, max_retries=0)
attempts = 3
start = time.perf_counter()
last_error = None

for attempt in range(1, attempts + 1):
    try:
        client.chat.completions.create(
            model="deepseek-flash",
            messages=[{"role": "user", "content": "你好"}],
        )
        say("    成功了（这次不会发生）")
        break
    except RETRYABLE_ERRORS as error:
        last_error = error
        waited = time.perf_counter() - start
        say(
            f"    第 {attempt} 次失败（累计 {waited:.1f}s）：{type(error).__name__}",
            f"      {str(error)[:70]}",
        )
        if attempt < attempts:
            delay = 0.3 * (2 ** (attempt - 1))
            say(f"      → 等 {delay:.1f}s 再试")
            time.sleep(delay)
    except openai.APIError as error:
        # 不是「值得重试」的那类（401、400、404 这些），直接放弃，别浪费次数
        say(f"    这类错误不该重试，直接报错：{type(error).__name__}")
        break

say(
    "",
    f"  三次都失败之后，交给用户的是最后那个错误：{type(last_error).__name__}",
    "  而程序**没有崩**——这就是容错要的效果：重试交给程序，最后给一句人话。",
)


# ============================================================
section("5. 超时：不设的话，程序会永远挂着")
# ============================================================

say(
    "  OpenAI(...) 建客户端时可以给一个 timeout（秒）。为什么必须有：",
    "",
    "    · 不设的话，网络卡住时请求会一直挂着，用户看不到任何反馈；",
    "    · 昨天你试过 Ctrl+C——程序卡在网络读取里的时候，连它都不灵（要等数据回来才响应）；",
    "    · 设了之后，超时会抛 APITimeoutError，而这个恰好是「值得重试」的一类。",
    "",
    "  所以这几件事是连在一起的：**超时 → 抛出可重试的错误 → 退避重试 → 还不行就报人话**。",
)


