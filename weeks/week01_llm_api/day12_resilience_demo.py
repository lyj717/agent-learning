section("6. 上下文裁剪：为什么非做不可")
# ============================================================

say(
    "  Day 9 你算过那笔账：20 轮对话，输入 token 一共发了 12200 个，",
    "  而对话内容本身只有 1230 个——**9.9 倍是重复发送**。聊得越久，每一轮越贵、越慢。",
    "",
    "  常见策略（从简单到复杂）：",
    "    ① 丢了最早的：只保留最近 N 轮（最简单，本仓库选这个）",
    "    ② 滑动窗口 + 保留 system：system 永远留着，只删历史（比 ① 更正确）",
    "    ③ 摘要压缩：把早期对话让模型总结成一段话，再塞回去（最贵但信息损失最小）",
    "",
    "  ② 的规则很简单：**system 不参与裁剪，历史只留最近 N 轮。**",
)

system_message = {"role": "system", "content": "你是一个只说一句话的助手。"}
history = []
for turn in range(1, 7):
    history.append(
        {"role": "user", "content": f"第 {turn} 轮的问题（占一些 token 的文字）"}
    )
    history.append({"role": "assistant", "content": f"第 {turn} 轮的回答"})

KEEP_TURNS = 2
kept = history[-KEEP_TURNS * 2 :]
say(
    "",
    f"  演示：system + 6 轮历史，裁到只留最近 {KEEP_TURNS} 轮",
    f"    裁之前：{len(history) + 1} 条消息（含 system）",
    f"    裁之后：{len(kept) + 1} 条消息",
    "",
    "  裁完发出去的 messages：",
)
for message in [system_message, *kept]:
    say(f"    {message['role']:<9} {message['content']}")

say(
    "",
    "  代价也要说清楚：**被丢掉的那几轮，模型是真的看不见了**。",
    "  所以用户如果问「我一开始说的那个事」，它会答不上来——这是有意的取舍：",
    "  用「记得久」换「便宜、快、不超上下文窗口」。",
)


