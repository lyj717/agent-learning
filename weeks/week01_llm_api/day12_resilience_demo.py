section("7. 要注意什么")
# ============================================================

say(
    "  · 重试只包在「发请求」这一步；已经吐字给用户之后再重试，会重复输出半截答案。",
    "  · 重试次数要有上限（3 次差不多），不然用户会以为程序死了。",
    "  · 别把「用户按了 Ctrl+C」也当成网络错误去重试——那是用户不想要了。",
    "  · 裁剪时 system 一定要留着，否则机器人下一句就换人格了。",
    "  · 失败那一轮**别写进历史**：历史里留着一条没人回答的问句，后面每轮都会带上它。",
)


