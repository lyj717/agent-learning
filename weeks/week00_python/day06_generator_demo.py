section("5. 重头戏：流式输出就靠它")
# ============================================================

say(
    "这是什么：把「等着生成完整段话」变成「生成一个字就给你一个字」。",
    "为什么需要：模型生成一句话要好几秒。等它全说完再显示，用户就干等好几秒；",
    "           边生成边显示，用户立刻看到反应，心理上快得多。",
    "场景：所有聊天产品的打字机效果，就是这一节做的事。",
)
print()


def stream_reply(text: str, delay: float = 0.03):
    """模拟模型逐字返回：一个字一个字地 yield。"""
    for char in text:
        time.sleep(delay)  # 假装这是网络传输 + 模型生成的时间
        yield char


reply = "杭州今天 22 度，多云，风不大。"

say("  做法一：一次性拿到全部（现实里就是 stream=False）：")
print("    ", end="")
start = time.perf_counter()
whole = "".join(stream_reply(reply))
print(whole)
say(f"    用时 {time.perf_counter() - start:.2f} 秒——这段时间屏幕上一个字都没有。")
print()

say("  做法二：边生成边打印（现实里就是 stream=True）：")
print("    ", end="")
start = time.perf_counter()
first_char_at = 0.0
for index, char in enumerate(stream_reply(reply)):
    if index == 0:
        first_char_at = time.perf_counter() - start
    print(char, end="", flush=True)
elapsed = time.perf_counter() - start
print()
say(
    f"    总用时其实一样，都是 {elapsed:.2f} 秒；",
    f"    但第一个字出现在第 {first_char_at:.2f} 秒，不是第 {elapsed:.2f} 秒。",
    "",
    "  这就是 Day 6 验收标准那句话的答案：",
    "    总时间没有变短，但用户「开始看到东西」的时间从最后一刻提前到了第一刻。",
    "    等待感来自「什么都没有」，不是来自总时长。",
    "",
    "  两个打印参数是流式的关键：",
    '    end=""      不换行，让下一个字接在后面',
    "    flush=True  立刻推出去，不要等缓冲区攒满（不加的话可能整段一起冒出来）",
)


