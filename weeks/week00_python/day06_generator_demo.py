section("6. 什么时候用生成器表达式，什么时候用列表")
# ============================================================

say(
    "    只遍历一遍、数据量大      → 生成器表达式 (x for x in xs)",
    "    要反复用、要 len()、要下标 → 列表 [x for x in xs]",
    "",
    "  一个常见写法：当作参数传给函数时，可以省掉一层括号。",
    "    sum(x * x for x in range(10))      ← 不用写成 sum((x * x for x in ...))",
    f"    算一下：sum(x * x for x in range(10)) = {sum(x * x for x in range(10))}",
)


