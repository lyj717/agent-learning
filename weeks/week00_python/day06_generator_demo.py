section("7. 要注意什么")
# ============================================================

say(
    "  1. 只能遍历一次：第二次就是空的（第 3 节那个坑）",
    "  2. 调试时别直接 print(gen)——那只是一句自我介绍；",
    "     想看内容用 print(list(gen))，但注意这一步会把生成器抽干，之后就没了。",
    "  3. 生成器函数里写 return 只是「提前结束」，不是返回值；",
    "     想让调用方拿到结果，就得 yield 出去。",
    "  4. 生成器是同步的。要「异步地一个个产出」（比如读模型的流式响应），",
    "     得用 async def + yield，配合 async for 消费——那是 day06_async_demo.py 的内容。",
)


section("总结")
say(
    "1. 函数里有 yield 就是生成器函数；调用它只拿到对象，函数体不会立刻执行",
    "2. 每次 next/for 从上次停下的地方接着跑，交给你的那个值就是 yield 出来的",
    "3. 生成器只能遍历一次，且不占内存——适合一遍过、数据大、甚至无限长的场景",
    "4. 流式输出的原理就是它：总时间不变，但用户「开始看到东西」的时间提前了",
    '5. 打印逐字效果要配 end="" 和 flush=True',
)
