"""生成器：让函数「边算边给」，而不是一次算完。

每一节都是同一个顺序：
    这是什么 → 为什么需要它 → 一个具体场景 → 代码 → 要注意什么

运行：
    .venv\\Scripts\\python.exe weeks\\week00_python\\day06_generator_demo.py

这一天直接关系到 Week 01 的交付物：模型的流式回复就是靠生成器逐字吐出来的。
"""

import itertools
import sys
import time


def section(title: str) -> None:
    print(f"\n{'=' * 56}\n{title}\n{'=' * 56}")


def say(*lines: str) -> None:
    for line in lines:
        print(line)


# ============================================================
section("1. 先说 for 循环吃的是什么")
# ============================================================

say(
    "这是什么：能放进 for 循环的东西，Python 里叫「可迭代对象」。",
    "为什么先说它：for 拿到的东西不一定是一整个列表，",
    "           也可能是「你要一个它才算一个」的东西——那就是生成器。",
    "场景：读一个 10GB 的日志文件，不可能一次全读进内存。",
)
print()

squares_list = [n * n for n in range(5)]
squares_gen = (n * n for n in range(5))

say(
    f"  列表推导式（方括号）：{squares_list}",
    f"    它的类型是 {type(squares_list).__name__}，值已经全部算好放在内存里了",
    "",
    f"  生成器表达式（圆括号）：{squares_gen}",
    f"    它的类型是 {type(squares_gen).__name__}，打印出来只是一句自我介绍",
    "",
    "  关键差别：后者一个值都还没算。它只说了一句「等你要的时候我再算」。",
)


# ============================================================
section("2. yield：函数里有它，就变成了生成器函数")
# ============================================================

say(
    "这是什么：函数体里出现 yield，这个函数就不再是普通函数，而是「生成器函数」。",
    "为什么需要：普通函数 return 一次就结束；生成器可以一次次地「产出」值，",
    "           每次产出后停在原地，下次从停的地方接着跑。",
    "场景：倒数计时、逐行读文件、逐字吐模型回复。",
)
print()


def countdown(n: int):
    """从 n 数到 1，每数一个交出去一次。"""
    print("      【countdown 开始执行】")
    while n > 0:
        yield n
        n -= 1
    print("      【countdown 执行完了】")


say("  先做一件事：调用它，但不要遍历。")
gen = countdown(3)
say(
    f"    返回的东西是：{gen}",
    "    注意上面那两行【】一句都没打印——函数体压根还没开始跑。",
    "",
    "  调用生成器函数只做一件事：造出一个生成器对象。函数体要等你要值时才执行。",
    "",
    "  现在开始一个一个要：",
)

for value in gen:
    say(f"    for 拿到 {value}")

say(
    "",
    "  顺序复盘：每要一个值 → 函数体跑到下一个 yield 停住、把值交出来 →",
    "  下一次再要 → 从刚才停住的地方继续跑。",
    "  这就是「流式」两个字的全部原理：不准备完，也能先给你一部分。",
)


# ============================================================
section("3. 最容易踩的坑：生成器只能遍历一次")
# ============================================================

say(
    "  生成器内部只记着一个「我走到哪了」的位置。走到头，它就空了。",
)

gen = countdown(3)
first_total = sum(gen)
say(f"    第一次 sum(gen) = {first_total}")
second_total = sum(gen)
say(f"    第二次 sum(gen) = {second_total}")
say(
    "    第二次是 0，而且连【】都没打印——因为它已经走到头了，直接结束。",
    "",
    "  这跟列表完全不同：列表你遍历一百遍都是一样的。",
    "  所以生成器适合「一遍过」的场景（逐个处理、边读边写），",
    "  需要反复用同一批数据时，就老老实实转成 list：",
    "    data = list(your_generator())",
)


# ============================================================
section("4. 为什么要用它：惰性 + 省内存")
# ============================================================

say(
    "  第一个好处：可以表示「无限长」的序列。",
)


def fibonacci():
    """斐波那契数列：1, 1, 2, 3, 5, 8, ...（永远不会结束）"""
    a, b = 1, 1
    while True:
        yield a
        a, b = b, a + b


# islice(可迭代对象, 个数)：只取前 N 个。
# 它的好处是「惰性」——只问你真要的那几个，所以对无限长的生成器也能用
first_ten = list(itertools.islice(fibonacci(), 10))
say(
    "    这个函数里是个 while True，永远不会自己停。",
    "    但它不占内存、也不会卡死，因为你不问它就不算。",
    f"    取前 10 个：{first_ten}",
    "",
    "  第二个好处：省内存。同样一亿个数，列表要全部算完并占满内存，",
    "  生成器只算你真正要的那几个。",
)

numbers_list = [n for n in range(1000)]
numbers_gen = (n for n in range(1000))
# getsizeof(对象)：量这个对象自己占多少字节（不递归算它里面的东西）
say(
    "  同样是 1000 个数：",
    f"    列表占 {sys.getsizeof(numbers_list):>5} 字节",
    f"    生成器占 {sys.getsizeof(numbers_gen):>5} 字节",
    "    而且这个数字不会随数据量变大而变大——它只装了个「游标」。",
)


